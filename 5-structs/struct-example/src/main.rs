#[derive(Debug)]
struct Rectangle {
    width: u32,
    height: u32,
}

impl Rectangle {
    fn area(&self) -> u32 {
        self.width * self.height
    }

    fn peri(&self) -> u32 {
        self.width * 2 + self.height * 2
    }
}

fn main() {
    let rect1 = Rectangle {
        width: 30,
        height: 50,
    };

    println!(
        "The area of the rectangle is {} square pixels. Perimeter is {}",
        rect1.area(),
        rect1.peri(),
    );
}